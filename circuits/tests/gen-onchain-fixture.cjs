function toBufferBE(v, width) {
  let hex = BigInt(v).toString(16);
  if (hex.length > width * 2) throw new Error("value too large for " + width + " bytes");
  return Buffer.from(hex.padStart(width * 2, "0"), "hex");
}

const COMPRESSED = 0b10000000, INFINITY = 0b01000000, YBIT = 0b00100000;

function compressedG1(curve, point) {
  const result = toBufferBE(BigInt(point[0]), 48);
  result[0] |= COMPRESSED;
  if (BigInt(point[2]) !== 1n) { result[0] |= INFINITY; return result.toString("hex"); }
  const F = curve.G1.F;
  const x = F.fromObject(BigInt(point[0]));
  const x3b = F.add(F.mul(F.square(x), x), curve.G1.b);
  const y1 = F.toObject(F.sqrt(x3b));
  const y2 = F.toObject(F.neg(F.sqrt(x3b)));
  const y = BigInt(point[1]);
  if ((y1 > y2 && y > y2) || (y1 < y2 && y > y1)) result[0] |= YBIT;
  return result.toString("hex");
}

function compressedG2(curve, point) {
  const result = Buffer.concat([toBufferBE(BigInt(point[0][1]), 48), toBufferBE(BigInt(point[0][0]), 48)]);
  result[0] |= COMPRESSED;
  if (BigInt(point[2][0]) !== 1n) { result[0] |= INFINITY; return result.toString("hex"); }
  const F = curve.G2.F;
  const x = F.fromObject(point[0].map((i) => BigInt(i)));
  const x3b = F.add(F.mul(F.square(x), x), curve.G2.b);
  const y1 = F.toObject(F.sqrt(x3b));
  const y2 = F.toObject(F.neg(F.sqrt(x3b)));
  const gt = (a, b) => a[1] > b[1] || (a[1] === b[1] && a[0] > b[0]);
  const y = point[1].map((i) => BigInt(i));
  if ((gt(y1, y2) && gt(y, y2)) || (gt(y2, y1) && gt(y, y1))) result[0] |= YBIT;
  return result.toString("hex");
}

async function main() {
  const secret = 88553311220099887766554433221100998877n;
  const collateral_amount = 20_000_000n, loan_amount = 10_000_000n, collateral_ratio = 125n;
  const commitment = poseidon2([collateral_amount, secret]);
  const input = {
    commitment: commitment.toString(),
    loan_amount: loan_amount.toString(),
    collateral_ratio: collateral_ratio.toString(),
    secret: secret.toString(),
    collateral_amount: collateral_amount.toString(),
  };

  const { proof, publicSignals } = await snarkjs.groth16.fullProve(input, WASM, ZKEY);
  if (!(await snarkjs.groth16.verify(VKEY, publicSignals, proof))) throw new Error("off-chain verify failed");

  const curve = await ff.getCurveFromName("bls12381");
  const piA = compressedG1(curve, proof.pi_a);
  const piB = compressedG2(curve, proof.pi_b);
  const piC = compressedG1(curve, proof.pi_c);
  const vkAlpha = compressedG1(curve, VKEY.vk_alpha_1);
  const vkBeta = compressedG2(curve, VKEY.vk_beta_2);
  const vkGamma = compressedG2(curve, VKEY.vk_gamma_2);
  const vkDelta = compressedG2(curve, VKEY.vk_delta_2);
  const vkIC = VKEY.IC.map((p) => compressedG1(curve, p));
  await curve.terminate();

  const icLit = vkIC.map((h) => `#"${h}"`).join(", ");
  const cmt = publicSignals[0];
  const loan = publicSignals[1];
  const ratio = publicSignals[2];
  const loanTampered = (BigInt(loan) + 1n).toString();

  const ak = `// AUTO-GENERATED by circuits/tests/gen-onchain-fixture.cjs — do not edit by hand.
// Real BLS12-381 Groth16 proof for the collateral circuit, verified on-chain
// via zk.verify_collateral_proof (the exact helper the v5 validators call).
// Proves Milestone 3's core claim: zk-SNARK proofs are verifiable ON-CHAIN.
use ak_381/groth16.{Proof, SnarkVerificationKey}
use zk.{verify_collateral_proof}

fn vkey() -> SnarkVerificationKey {
  SnarkVerificationKey {
    nPublic: ${VKEY.nPublic},
    vkAlpha: #"${vkAlpha}",
    vkBeta: #"${vkBeta}",
    vkGamma: #"${vkGamma}",
    vkDelta: #"${vkDelta}",
    vkAlphaBeta: [],
    vkIC: [${icLit}],
  }
}

fn proof() -> Proof {
  Proof { piA: #"${piA}", piB: #"${piB}", piC: #"${piC}" }
}

// Public signals: [commitment, loan_amount, collateral_ratio]
test collateral_proof_verifies_onchain() {
  verify_collateral_proof(vkey(), proof(), ${cmt}, ${loan}, ${ratio})
}

test tampered_public_signal_fails_onchain() {
  !verify_collateral_proof(vkey(), proof(), ${cmt}, ${loanTampered}, ${ratio})
}
`;
  fs.writeFileSync(OUT, ak);
  console.log("Wrote", OUT);
  console.log("public signals:", publicSignals);
  console.log("piA/piB/piC bytes:", piA.length / 2, piB.length / 2, piC.length / 2);
  console.log("vkIC count:", vkIC.length);
  process.exit(0);
}

main().catch((e) => { console.error("FATAL:", e); process.exit(1); });
